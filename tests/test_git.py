"""Git auto-commit: commits, messages, README, links, and pushing to a local test remote."""

import os
import subprocess
import unittest

from helpers import APP, TempConfig

from PySide6.QtCore import QEventLoop, QTimer

from actuator import config as cfg, gitsync, writer

ENV = dict(os.environ, GIT_AUTHOR_NAME="t", GIT_AUTHOR_EMAIL="t@t", GIT_COMMITTER_NAME="t",
           GIT_COMMITTER_EMAIL="t@t")


def git(*args, cwd):
    return subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True, env=ENV)


class GitTests(TempConfig):
    def setUp(self):
        super().setUp()
        os.environ.update({k: ENV[k] for k in ("GIT_AUTHOR_NAME", "GIT_AUTHOR_EMAIL",
                                              "GIT_COMMITTER_NAME", "GIT_COMMITTER_EMAIL")})
        self.remote = self.dir / "remote.git"
        git("init", "-q", "--bare", str(self.remote), cwd=self.dir)
        git("init", "-q", "-b", "main", cwd=self.dir)
        (self.dir / "other.txt").write_text("someone else's file\n")
        git("add", "config.yaml", cwd=self.dir)
        git("commit", "-qm", "init", cwd=self.dir)
        git("remote", "add", "origin", str(self.remote), cwd=self.dir)
        git("push", "-q", "-u", "origin", "main", cwd=self.dir)

    def test_status(self):
        st = gitsync.status(self.path)
        self.assertTrue(st["git"])
        self.assertEqual(st["repo"].resolve(), self.dir.resolve())
        self.assertIn("origin", st["remote"])

    def test_commit_only_config_and_readme(self):
        old = self.path.read_text()
        c = cfg.load(self.path)
        next(b for b in c.bindings if b.id == "factorio_forward").data["actions"][0]["input"][0]["keyboard"] = ["q"]
        writer.save(c)
        readme = self.dir / "README.md"
        readme.write_text(gitsync.readme(cfg.load(self.path)))
        msg = gitsync.message(old, self.path.read_text())
        self.assertTrue(msg.startswith("Actuator: Factorio: ~ Forward: E → Q"))
        ok, out = gitsync.commit(self.path, msg, [readme])
        self.assertTrue(ok, out)
        files = git("show", "--name-only", "--format=", "HEAD", cwd=self.dir).stdout.split()
        self.assertEqual(sorted(files), ["README.md", "config.yaml"])
        self.assertIn("?? other.txt", git("status", "--short", cwd=self.dir).stdout)  # left alone
        self.assertEqual(gitsync.commit(self.path, msg), (True, "nothing to commit"))

    def test_backup_commit_even_when_unchanged(self):
        ok, out = gitsync.commit(self.path, "Actuator: backup", allow_empty=True)
        self.assertTrue(ok, out)
        self.assertEqual(git("log", "--format=%s", "-1", cwd=self.dir).stdout.strip(), "Actuator: backup")
        self.assertIn("?? other.txt", git("status", "--short", cwd=self.dir).stdout)  # left alone

    def test_readme_contents(self):
        text = gitsync.readme(cfg.load(self.path))
        self.assertTrue(text.startswith("> This README was automatically generated by [Actuator]"))
        self.assertIn("## Global", text)
        self.assertIn("## Firefox", text)
        self.assertIn("| Only if |", text)                 # firefox close has a condition
        self.assertIn("| Trigger | Action |", text)
        self.assertIn("window is fullscreen", text)
        self.assertIn("| Back | Hold F |", text)          # hold bindings read simply
        self.assertIn("on begin: Hold Alt, Tab", text)     # multi-step spelled out
        self.assertNotIn("hover", text.lower())            # pointer tab is hidden
        self.assertIn("## Device settings", text)

    def test_readme_groups_apps_under_their_folders(self):
        c = cfg.load(self.path)
        c.move_to_folder("factorio", "Gaming")
        headings = [l for l in gitsync.readme(c).splitlines() if l.startswith("#")]
        self.assertLess(headings.index("## Gaming"), headings.index("### Factorio"))
        self.assertLess(headings.index("## Uncategorized"), headings.index("### Firefox"))  # the rest
        self.assertNotIn("## Factorio", headings)

    def test_links(self):
        git("remote", "set-url", "origin", "git@github.com:me/configs.git", cwd=self.dir)
        self.assertEqual(gitsync.web_url(self.dir), "https://github.com/me/configs")
        self.assertRegex(gitsync.commit_url(self.dir), r"^https://github.com/me/configs/commit/[0-9a-f]{40}$")

    def test_push_in_background(self):
        (self.path).write_text(self.path.read_text() + "\n# change\n")
        gitsync.commit(self.path, "Actuator: test")
        results = []
        pusher = gitsync.Pusher()
        loop = QEventLoop()
        pusher.done.connect(lambda ok, out: (results.append(ok), loop.quit()))
        pusher.push(self.dir)
        QTimer.singleShot(10_000, loop.quit)
        loop.exec()
        self.assertEqual(results, [True])
        self.assertIn("Actuator: test", git("log", "--format=%s", "-1", "main", cwd=self.remote).stdout)


if __name__ == "__main__":
    unittest.main()
